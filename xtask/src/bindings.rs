//! `xtask bindings`: run bindgen over the libmpv client headers and write `crates/player/src/sys/bindings.rs`.

use std::fs;
use std::path::Path;

use crate::binaries;

const HEADERS: &[&str] = &["mpv/client.h", "mpv/render.h", "mpv/render_gl.h", "mpv/stream_cb.h"];

pub fn run() {
    let include = binaries::locate_binaries().join("include");
    let wrapper: String = HEADERS.iter().map(|h| format!("#include <{h}>\n")).collect();

    let bindings = bindgen::Builder::default()
        .header_contents("wrapper.h", &wrapper)
        .clang_arg(format!("-I{}", include.display()))
        .allowlist_function("mpv_.*")
        .allowlist_type("mpv_.*")
        .allowlist_var("MPV_.*")
        // C enums become plain constants (`MPV_FORMAT_STRING`) of a type alias (`mpv_format`).
        .default_enum_style(bindgen::EnumVariation::Consts)
        .prepend_enum_name(false)
        // The header comments contain indented C snippets that rustdoc would run as doctests; the headers stay the
        // reference for the raw API.
        .generate_comments(false)
        .layout_tests(false)
        .formatter(bindgen::Formatter::Prettyplease)
        .generate()
        .expect("xtask: bindgen failed to generate bindings from the mpv headers");

    let client_h = fs::read_to_string(include.join("mpv/client.h")).expect("xtask: cannot read mpv/client.h");
    let (major, minor) = client_api_version(&client_h);

    let mut out = format!(
        "// Generated by `cargo run -p xtask -- bindings` from binaries-mpv {}. Do not edit.\n\n",
        binaries::version()
    );
    out.push_str(&enums_as_c_int(&bindings.to_string()));
    out.push_str(&format!(
        "\n/// `MPV_CLIENT_API_VERSION` of the headers these bindings were generated from: `(major << 16) | minor`.\n\
         pub const MPV_CLIENT_API_VERSION: ::std::os::raw::c_ulong = ({major} << 16) | {minor};\n"
    ));

    let repo_root = Path::new(env!("CARGO_MANIFEST_DIR")).parent().expect("xtask: no parent dir");
    let path = repo_root.join("crates/player/src/sys/bindings.rs");
    fs::write(&path, out).unwrap_or_else(|e| panic!("xtask: failed to write {}: {e}", path.display()));
    eprintln!("xtask: wrote {}", path.display());
}

/// Gives every C enum the `c_int` representation. Clang picks `unsigned int` for enums without negative values on
/// GCC/Clang targets but `int` on MSVC; fixing one type keeps the committed file identical on every target.
fn enums_as_c_int(code: &str) -> String {
    const UINT_ALIAS: &str = " = ::std::os::raw::c_uint;";
    code.lines()
        .map(|line| {
            let enum_name = line.strip_prefix("pub type ").and_then(|l| l.strip_suffix(UINT_ALIAS));
            match enum_name {
                Some(name) if code.contains(&format!(": {name} = ")) => {
                    format!("pub type {name} = ::std::os::raw::c_int;\n")
                }
                _ => format!("{line}\n"),
            }
        })
        .collect()
}

/// Reads `#define MPV_CLIENT_API_VERSION MPV_MAKE_VERSION(major, minor)`, which bindgen cannot evaluate because it is
/// a function-like macro invocation.
fn client_api_version(client_h: &str) -> (u16, u16) {
    let args = client_h
        .lines()
        .find_map(|l| l.strip_prefix("#define MPV_CLIENT_API_VERSION MPV_MAKE_VERSION("))
        .and_then(|rest| rest.split_once(')'))
        .map(|(args, _)| args)
        .expect("xtask: MPV_CLIENT_API_VERSION not found in mpv/client.h");
    let (major, minor) = args.split_once(',').expect("xtask: malformed MPV_CLIENT_API_VERSION");
    let parse = |s: &str| s.trim().parse().expect("xtask: malformed MPV_CLIENT_API_VERSION");
    (parse(major), parse(minor))
}
